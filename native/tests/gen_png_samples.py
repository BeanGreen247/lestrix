#!/usr/bin/env python3
# Regenerates tests/png_samples.h: PNG files covering every colour type, filter and deflate block type vgfx's decoder supports,
# each with the RGBA words (r | g<<8 | b<<16 | a<<24) a correct decoder must produce.
import struct, zlib, random
random.seed(5)

def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)

def paeth(a, b, c):
    p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    return a if pa <= pb and pa <= pc else b if pb <= pc else c

def filt(ft, row, prev, bpp):
    out = bytearray()
    for i, x in enumerate(row):
        a = row[i - bpp] if i >= bpp else 0
        b = prev[i]
        c = prev[i - bpp] if i >= bpp else 0
        pred = [0, a, b, (a + b) >> 1, paeth(a, b, c)][ft]
        out.append((x - pred) & 255)
    return bytes([ft]) + bytes(out)

def png(w, h, ctype, rows, level=6, strategy=zlib.Z_DEFAULT_STRATEGY, plte=None, trns=None):
    ch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    raw = b""; prev = bytes(w * ch)
    for y, r in enumerate(rows):
        raw += filt(y % 5, r, prev, ch); prev = r
    co = zlib.compressobj(level, zlib.DEFLATED, 15, 8, strategy)
    z = co.compress(raw) + co.flush()
    out = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, ctype, 0, 0, 0))
    if plte: out += chunk(b"PLTE", plte)
    if trns: out += chunk(b"tRNS", trns)
    half = len(z) // 2
    out += chunk(b"IDAT", z[:half]) + chunk(b"IDAT", z[half:]) + chunk(b"IEND", b"")
    return out

def word(r, g, b, a=255): return r | g << 8 | b << 16 | a << 24

samples = []
def add(name, data, exp, w, h): samples.append((name, data, exp, w, h))

rnd = lambda n: bytes(random.randrange(256) for _ in range(n))
rows = [rnd(12) for _ in range(3)]
add("RGBA", png(3, 3, 6, rows), [word(r[i], r[i+1], r[i+2], r[i+3]) for r in rows for i in range(0, 12, 4)], 3, 3)
rows = [rnd(6) for _ in range(5)]
add("RGB_STORED", png(2, 5, 2, rows, level=0), [word(r[i], r[i+1], r[i+2]) for r in rows for i in range(0, 6, 3)], 2, 5)
rows = [bytes([0, 128, 255, 7])]
add("GRAY_FIXED", png(4, 1, 0, rows, strategy=zlib.Z_FIXED), [word(v, v, v) for v in rows[0]], 4, 1)
rows = [bytes([10, 200, 30, 40])]
add("GRAYALPHA", png(2, 1, 4, rows), [word(10, 10, 10, 200), word(30, 30, 30, 40)], 2, 1)
pal = bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 9, 8, 7])
rows = [bytes([0, 1, 2, 3, 3, 0])]
add("PALETTE_TRNS", png(6, 1, 3, rows, plte=pal, trns=bytes([255, 128])), [word(255, 0, 0), word(0, 255, 0, 128), word(0, 0, 255, 255), word(9, 8, 7, 255), word(9, 8, 7, 255), word(255, 0, 0)], 6, 1)
W, H = 100, 60
rows = [bytes(((x * 3 + y * 5 + c * 40) & 255 if (x // 7 + y // 5) % 3 else random.randrange(256)) for x in range(W) for c in range(3)) for y in range(H)]
add("RGB_DYNAMIC", png(W, H, 2, rows, level=9), [word(r[i], r[i+1], r[i+2]) for r in rows for i in range(0, W * 3, 3)], W, H)

with open("tests/png_samples.h", "w") as f:
    f.write("/* generated by tests/gen_png_samples.py */\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    for n, d, e, w, h in samples:
        f.write(f"static const uint8_t PNG_{n}[] = {{" + ",".join(map(str, d)) + "};\n")
        f.write(f"static const uint32_t PNG_{n}_PX[] = {{" + ",".join(f"0x{x:08x}u" for x in e) + "};\n")
        f.write(f"enum {{ PNG_{n}_W = {w}, PNG_{n}_H = {h} }};\n")
    raw = bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 1, 2, 3])
    z = zlib.compress(raw)
    f.write("static const uint8_t ZRAW_RGB_2X2[] = {" + ",".join(map(str, z)) + "};\n")
print("ok", [(n, len(d)) for n, d, *_ in samples])
